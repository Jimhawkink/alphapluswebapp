-- 1. SUPPLIERS TABLE
CREATE TABLE IF NOT EXISTS public.suppliers (
  supplier_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_code character varying(50) UNIQUE,
  supplier_name character varying(255) NOT NULL,
  contact_person character varying(255),
  phone character varying(50),
  phone2 character varying(50),
  email character varying(255),
  address text,
  city character varying(100),
  kra_pin character varying(50),
  opening_balance numeric(15,2) DEFAULT 0,
  balance_type character varying(20) DEFAULT 'Credit', -- 'Credit' (We Owe) or 'Debit' (They Owe)
  current_balance numeric(15,2) DEFAULT 0,
  payment_terms character varying(100), -- e.g. 'Net 30', 'COD', 'Cash'
  is_kitchen boolean DEFAULT false,
  active boolean DEFAULT true,
  notes text,
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now()
);

-- 2. PURCHASES (HEADER) TABLE
CREATE TABLE IF NOT EXISTS public.purchases (
  purchase_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_no character varying(50) NOT NULL UNIQUE,
  purchase_date date NOT NULL DEFAULT CURRENT_DATE,
  supplier_id integer REFERENCES public.suppliers(supplier_id) ON DELETE SET NULL,
  supplier_name character varying(255),
  supplier_invoice character varying(100),
  sub_total numeric(15,2) DEFAULT 0,
  discount numeric(15,2) DEFAULT 0,
  vat numeric(15,2) DEFAULT 0,
  grand_total numeric(15,2) DEFAULT 0,
  status character varying(50) DEFAULT 'Completed', -- 'Completed', 'Pending', 'Draft'
  payment_status character varying(50) DEFAULT 'Paid', -- 'Paid', 'Unpaid', 'Partial'
  notes text,
  created_by character varying(100),
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now()
);

-- 3. PURCHASE_PRODUCTS (LINE ITEMS) TABLE
CREATE TABLE IF NOT EXISTS public.purchase_products (
  pp_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_id integer NOT NULL REFERENCES public.purchases(purchase_id) ON DELETE CASCADE,
  product_id integer,
  product_code character varying(100),
  product_name character varying(255) NOT NULL,
  unit character varying(50) DEFAULT 'PCS',
  quantity numeric(15,3) NOT NULL DEFAULT 0,
  rate numeric(15,2) NOT NULL DEFAULT 0,
  total_amount numeric(15,2) NOT NULL DEFAULT 0,
  created_at timestamp with time zone DEFAULT now()
);

-- 4. INDEXES FOR HIGH-SPEED QUERIES
CREATE INDEX IF NOT EXISTS idx_suppliers_code ON public.suppliers(supplier_code);
CREATE INDEX IF NOT EXISTS idx_suppliers_name ON public.suppliers(supplier_name);
CREATE INDEX IF NOT EXISTS idx_purchases_no ON public.purchases(purchase_no);
CREATE INDEX IF NOT EXISTS idx_purchases_date ON public.purchases(purchase_date);
CREATE INDEX IF NOT EXISTS idx_purchases_supplier ON public.purchases(supplier_id);
CREATE INDEX IF NOT EXISTS idx_purchase_products_purchase ON public.purchase_products(purchase_id);
CREATE INDEX IF NOT EXISTS idx_purchase_products_product ON public.purchase_products(product_id);

-- 5. ROW LEVEL SECURITY & PERMISSIONS
ALTER TABLE public.suppliers DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.purchases DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.purchase_products DISABLE ROW LEVEL SECURITY;

GRANT ALL ON public.suppliers TO anon, authenticated, service_role;
GRANT ALL ON public.purchases TO anon, authenticated, service_role;
GRANT ALL ON public.purchase_products TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

